"""Connection multiplexing.

sshfleet writes its own ``ssh_config`` that ``Include``s the operator's environment files and
adds a ``Host *`` block with ``ControlMaster auto``. OpenSSH passes ``-F`` down to the
``ProxyJump`` hop, so the bastion connection is multiplexed too and every later command reuses
both sockets — that is what makes a 48-host refresh take about a second.

The tool records key *paths* from the config and never opens a key file.
"""

from __future__ import annotations

import asyncio
import contextlib
import os
from dataclasses import dataclass
from pathlib import Path

from ..config import Config, ConfigError
from ..inventory import EnvScope, Inventory, common_prefix
from ..paths import Paths
from . import argv as A
from . import proc as proc_module
from .errors import ErrorKind, SshError, classify, first_line

HEADER = "# Generated by sshfleet — do not edit; regenerated when environments change.\n"

#: OpenSSH tries these when no IdentityFile is configured — but naming one *replaces* the list,
#: so we re-add the ones that exist to stay strictly additive for hosts that use a default key.
DEFAULT_IDENTITIES = (
    "~/.ssh/id_ed25519",
    "~/.ssh/id_ecdsa",
    "~/.ssh/id_rsa",
    "~/.ssh/id_dsa",
)


def _existing_default_identities() -> list[str]:
    """Default identity paths that exist (checked with stat; the files are never opened)."""
    return [path for path in DEFAULT_IDENTITIES if Path(path).expanduser().exists()]


def _one_line(value: object, what: str) -> str:
    """A configured value as it goes into the generated config: on one line, or refused.

    The file is written line by line, so a value carrying a line break would add lines of its
    own — a ``ProxyCommand``, say, which ssh runs on this machine. The settings page, a
    hand-edited config and an imported bundle all end up here.
    """
    text = str(value)
    if any(ord(ch) < 32 or ch == "\x7f" for ch in text):
        raise ConfigError(f"{what} contains a line break or a control character: {text!r}")
    return text


def _render_alias_match(prefix: str | None, aliases: list[str]) -> list[str]:
    """``Host acme-prod-*`` when there is a shared prefix, else explicit alias lines."""
    if prefix:
        return [f"Host {prefix}*"]
    lines = []
    for start in range(0, len(aliases), 8):
        lines.append("Host " + " ".join(aliases[start : start + 8]))
    return lines


@dataclass(slots=True)
class MuxResult:
    alias: str
    ok: bool
    kind: ErrorKind | None = None
    message: str = ""
    elapsed: float = 0.0


class MuxManager:
    """Owns the generated ssh_config and the ControlMaster sockets."""

    def __init__(self, config: Config, paths: Paths, inventory: Inventory | None = None) -> None:
        self.config = config
        self.paths = paths
        self.inventory = inventory
        self.alive: set[str] = set()
        self._locks: dict[str, asyncio.Lock] = {}

    # ---------------------------------------------------------------- config

    @property
    def ssh_config(self) -> Path:
        return self.paths.ssh_config

    def control_dir(self) -> Path:
        configured = self.config.ssh.control_dir
        if configured and configured != "auto":
            return Path(configured).expanduser()
        return self.paths.control_dir

    def render_config(self) -> str:
        ssh = self.config.ssh
        control = _one_line(self.control_dir(), "ssh.control_dir")
        lines = [
            HEADER,
            "Host *\n",
            "    ControlMaster auto\n",
            f"    ControlPath {control}/%C\n",
            f"    ControlPersist {_one_line(ssh.control_persist, 'ssh.control_persist')}\n",
            f"    ServerAliveInterval {_one_line(ssh.server_alive_interval_s, 'ssh.server_alive_interval_s')}\n",
            "    ServerAliveCountMax 3\n",
            f"    ConnectTimeout {_one_line(ssh.connect_timeout_s, 'ssh.connect_timeout_s')}\n",
            "    BatchMode yes\n",
        ]
        if ssh.compression:
            lines.append("    Compression yes\n")
        lines += [
            f"    StrictHostKeyChecking {_one_line(ssh.strict_host_key_checking, 'ssh.strict_host_key_checking')}\n",
            "    UpdateHostKeys no\n",
            "    LogLevel ERROR\n",
        ]

        for env_cfg in self.config.environments:
            lines.append(f"\n# environment: {_one_line(env_cfg.name, 'environment name')}\n")
            if env_cfg.key_path:
                # Inner hosts behind the bastion carry no IdentityFile of their own; add the
                # environment key for the whole alias pattern. IdentityFile is additive, so
                # default identities and any agent keys still work.
                aliases: list[str] = []
                prefix: str | None = None
                if env_cfg.alias_pattern != "auto":
                    prefix = _one_line(env_cfg.alias_pattern, f"{env_cfg.name}: alias_pattern").rstrip("*")
                elif self.inventory is not None:
                    with contextlib.suppress(KeyError):
                        environment = self.inventory.environment(env_cfg.id)
                        aliases = [h.alias for h in environment.hosts]
                        prefix = environment.alias_prefix or common_prefix(aliases)
                if prefix or aliases:
                    for host_line in _render_alias_match(prefix, aliases):
                        lines.append(host_line + "\n")
                    lines.append(f"    IdentityFile {_one_line(env_cfg.key_path, f'{env_cfg.name}: key_path')}\n")
                    # Naming an IdentityFile drops OpenSSH's built-in defaults, which would
                    # break any host that authenticates with ~/.ssh/id_* — re-add them.
                    for default in _existing_default_identities():
                        lines.append(f"    IdentityFile {default}\n")
            # An Include inside a Host block is conditional in OpenSSH: the file would be read
            # only for hosts matching the key pattern above (or the previous environment's), and
            # every other alias in it would fail as "Could not resolve hostname".
            lines.append("Match all\n")
            lines.append(f"Include {_one_line(env_cfg.ssh_config_path, f'{env_cfg.name}: ssh_config_path')}\n")

        if self.config.ssh.include_user_config:
            lines.append("\nMatch all\nInclude ~/.ssh/config\n")
        return "".join(lines)

    def write_ssh_config(self) -> Path:
        """Write the generated config (0600) if its content changed."""
        path = self.ssh_config
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.control_dir().mkdir(parents=True, exist_ok=True, mode=0o700)
        text = self.render_config()
        if not path.exists() or path.read_text() != text:
            tmp = path.with_name(path.name + ".tmp")
            tmp.write_text(text)
            os.chmod(tmp, 0o600)
            os.replace(tmp, path)
        return path

    # ------------------------------------------------------------- processes

    async def _run(self, args: list[str], timeout: float) -> tuple[int, str, str]:
        result = await proc_module.run(args, timeout=timeout)
        if result.timed_out:
            raise TimeoutError(" ".join(args))
        return result.returncode, result.stdout.decode(errors="replace"), result.stderr.decode(errors="replace")

    def lock_for(self, alias: str) -> asyncio.Lock:
        """Serialise the *first* connection per alias so two clients don't race the master."""
        lock = self._locks.get(alias)
        if lock is None:
            lock = asyncio.Lock()
            self._locks[alias] = lock
        return lock

    async def check(self, alias: str) -> bool:
        """``ssh -O check`` — cheap, local, no network."""
        try:
            code, _, _ = await self._run(A.ssh_control_argv(self.ssh_config, alias, "check"), timeout=5)
        except (TimeoutError, asyncio.CancelledError):
            return False
        ok = code == 0
        if ok:
            self.alive.add(alias)
        else:
            self.alive.discard(alias)
        return ok

    def paused_reason(self, alias: str) -> str | None:
        return self.inventory.paused_reason(alias) if self.inventory is not None else None

    async def warm(self, alias: str, timeout: float = 25.0) -> MuxResult:
        """Open (or reuse) the master connection for an alias."""
        reason = self.paused_reason(alias)
        if reason is not None:
            return MuxResult(alias, False, ErrorKind.PAUSED, reason)
        loop = asyncio.get_running_loop()
        started = loop.time()
        async with self.lock_for(alias):
            if alias in self.alive and await self.check(alias):
                return MuxResult(alias, True, elapsed=loop.time() - started)
            try:
                code, _, err = await self._run(A.ssh_argv(self.ssh_config, alias, "true"), timeout=timeout)
            except TimeoutError:
                # Name the budget: a host that answers in 26s and is given 10 looks identical to
                # one that is dead, and the fix for each is the opposite of the other.
                return MuxResult(
                    alias,
                    False,
                    ErrorKind.TIMEOUT_CONNECT,
                    f"no connection within {timeout:g}s",
                    loop.time() - started,
                )
            elapsed = loop.time() - started
            kind = classify(code, err)
            if kind is None:
                self.alive.add(alias)
                return MuxResult(alias, True, elapsed=elapsed)
            if kind in {ErrorKind.MUX_STALE, ErrorKind.MUX_BROKEN}:
                await self.reset_socket(alias)
                code, _, err = await self._run(A.ssh_argv(self.ssh_config, alias, "true"), timeout=timeout)
                kind = classify(code, err)
                if kind is None:
                    self.alive.add(alias)
                    return MuxResult(alias, True, elapsed=loop.time() - started)
            self.alive.discard(alias)
            return MuxResult(alias, False, kind, first_line(err) or f"ssh exited {code}", elapsed)

    async def warm_bastions(self, env: EnvScope = None) -> dict[str, MuxResult]:
        """Open the bastion masters first; everything else rides on them."""
        if self.inventory is None:
            return {}
        # A paused bastion is left alone, and so is everything behind it (the fleet skips those).
        aliases = [a for a in self.inventory.bastions(env) if self.paused_reason(a) is None]
        if not aliases:
            return {}
        results = await asyncio.gather(*(self.warm(a) for a in aliases), return_exceptions=True)
        out: dict[str, MuxResult] = {}
        for alias, result in zip(aliases, results, strict=True):
            if isinstance(result, BaseException):
                out[alias] = MuxResult(alias, False, ErrorKind.UNKNOWN, str(result))
            else:
                out[alias] = result
        return out

    async def stop(self, alias: str) -> bool:
        try:
            code, _, _ = await self._run(A.ssh_control_argv(self.ssh_config, alias, "exit"), timeout=5)
        except (TimeoutError, asyncio.CancelledError):
            return False
        self.alive.discard(alias)
        return code == 0

    async def stop_all(self) -> list[str]:
        stopped = []
        for alias in sorted(self.alive):
            if await self.stop(alias):
                stopped.append(alias)
        return stopped

    async def forward(self, alias: str, spec: str) -> None:
        """``ssh -O forward -L <spec>`` on the existing master."""
        reason = self.paused_reason(alias)
        if reason is not None:
            raise SshError(ErrorKind.PAUSED, alias, reason)
        code, _, err = await self._run(A.ssh_control_argv(self.ssh_config, alias, "forward", "-L", spec), timeout=10)
        if code != 0:
            raise SshError(classify(code, err) or ErrorKind.UNKNOWN, alias, first_line(err) or "forward failed", err, code)

    async def cancel(self, alias: str, spec: str) -> None:
        code, _, err = await self._run(A.ssh_control_argv(self.ssh_config, alias, "cancel", "-L", spec), timeout=10)
        if code != 0:
            raise SshError(classify(code, err) or ErrorKind.UNKNOWN, alias, first_line(err) or "cancel failed", err, code)

    # ----------------------------------------------------------------- state

    async def control_path(self, alias: str) -> Path | None:
        """Ask ssh where this alias's socket lives (exact, and cheap)."""
        try:
            code, out, _ = await self._run([A.ssh_bin(), "-F", str(self.ssh_config), "-G", alias], timeout=5)
        except (TimeoutError, asyncio.CancelledError):
            return None
        if code != 0:
            return None
        for line in out.splitlines():
            if line.lower().startswith("controlpath "):
                value = line.split(None, 1)[1].strip()
                return Path(value).expanduser() if value and value != "none" else None
        return None

    async def reset_socket(self, alias: str) -> bool:
        """Remove this alias's stale socket. Only ever touches files in our own control dir."""
        self.alive.discard(alias)
        socket = await self.control_path(alias)
        directory = self.control_dir().resolve()
        if socket is None:
            return False
        try:
            if socket.resolve().parent != directory:
                return False  # never unlink outside the directory we own
        except OSError:
            return False
        with contextlib.suppress(OSError):
            socket.unlink()
            return True
        return False

    def reset_all(self) -> int:
        """Delete every socket in our control dir (``sshfleet mux reset``)."""
        removed = 0
        directory = self.control_dir()
        if directory.is_dir():
            for socket in directory.iterdir():
                with contextlib.suppress(OSError):
                    if socket.is_socket():
                        socket.unlink()
                        removed += 1
        self.alive.clear()
        return removed

    async def status(self, aliases: list[str]) -> dict[str, bool]:
        results = await asyncio.gather(*(self.check(a) for a in aliases), return_exceptions=True)
        return {
            alias: (result is True)
            for alias, result in zip(aliases, results, strict=True)
        }
